//! `zdx ask-media` routes audio to non-Gemini providers by the `input_audio`
//! declaration in `model_overrides.toml`. A model the binary has never heard of
//! works once the user declares it, and a provider the binary has never heard
//! of works as `[providers.custom.<name>]` with an `audio` block: no Rust code
//! names either. A regenerated `models.toml` without the model does not matter.

use std::sync::{Arc, Mutex};

use serde_json::{Value, json};
use tempfile::TempDir;
use wiremock::matchers::{method, path};
use wiremock::{Mock, MockServer, Request, ResponseTemplate};

/// A tiny but valid RIFF/WAV header plus two silent samples. The adapter sends
/// the bytes as-is, so no ffmpeg is involved.
const WAV: &[u8] = &[
    b'R', b'I', b'F', b'F', 40, 0, 0, 0, b'W', b'A', b'V', b'E', b'f', b'm', b't', b' ', 16, 0, 0,
    0, 1, 0, 1, 0, 0x80, 0x3e, 0, 0, 0, 0x7d, 0, 0, 2, 0, 16, 0, b'd', b'a', b't', b'a', 4, 0, 0,
    0, 0, 0, 0, 0,
];

/// What a regenerated registry looks like: the declared model is absent.
const REGENERATED_MODELS_TOML: &str = r#"# Generated by zdx models update

[[model]]
id = "stepfun:step-3.7-flash"
provider = "stepfun"
display_name = "Step 3.7 Flash"
context_limit = 1000

[model.pricing]
input = 0.0
output = 0.0
cache_read = 0.0
cache_write = 0.0
"#;

struct Run {
    home: TempDir,
    work: TempDir,
    clip: std::path::PathBuf,
}

fn setup(overrides: Option<&str>) -> Run {
    setup_with_config(overrides, None)
}

fn setup_with_config(overrides: Option<&str>, config: Option<&str>) -> Run {
    let home = TempDir::new().unwrap();
    let work = TempDir::new().unwrap();
    std::fs::write(home.path().join("models.toml"), REGENERATED_MODELS_TOML).unwrap();
    if let Some(config) = config {
        std::fs::write(home.path().join("config.toml"), config).unwrap();
    }
    if let Some(overrides) = overrides {
        std::fs::write(home.path().join("model_overrides.toml"), overrides).unwrap();
    }
    let clip = work.path().join("clip.wav");
    std::fs::write(&clip, WAV).unwrap();
    Run { home, work, clip }
}

fn ask(run: &Run, base_url: &str, model: &str) -> assert_cmd::assert::Assert {
    crate::fixtures::zdx_cmd()
        .env("ZDX_HOME", run.home.path())
        .env("STEPFUN_API_KEY", "test-api-key")
        .env("STEPFUN_BASE_URL", base_url)
        .current_dir(run.work.path())
        .args([
            "ask-media",
            "--json",
            "-m",
            model,
            "-p",
            "What is said?",
            run.clip.to_str().unwrap(),
        ])
        .assert()
}

/// Mounts a mock Chat Completions endpoint and returns the captured
/// `(authorization, body)` pairs.
async fn mock_chat(server: &MockServer) -> Arc<Mutex<Vec<(String, Value)>>> {
    let seen: Arc<Mutex<Vec<(String, Value)>>> = Arc::default();
    let seen_clone = Arc::clone(&seen);
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(move |req: &Request| {
            let auth = req
                .headers
                .get("authorization")
                .and_then(|v| v.to_str().ok())
                .unwrap_or_default()
                .to_string();
            let body: Value = serde_json::from_slice(&req.body).unwrap_or(Value::Null);
            seen_clone.lock().unwrap().push((auth, body));
            ResponseTemplate::new(200).set_body_json(json!({
                "choices": [{ "finish_reason": "stop", "message": { "content": "silence" } }]
            }))
        })
        .expect(1)
        .mount(server)
        .await;
    seen
}

#[tokio::test]
async fn user_declared_model_uses_the_existing_adapter_without_a_rebuild() {
    let run = setup(Some(
        r#"
[[override]]
id = "stepfun:audio-model-a"
input_audio = true
"#,
    ));
    let server = MockServer::start().await;
    let seen = mock_chat(&server).await;

    let output = ask(
        &run,
        &format!("{}/v1", server.uri()),
        "stepfun:audio-model-a",
    )
    .success()
    .get_output()
    .stdout
    .clone();
    let answer: Value = serde_json::from_slice(&output).unwrap();
    assert_eq!(answer["answer"], "silence");
    assert_eq!(answer["model"], "stepfun:audio-model-a");

    let (auth, body) = seen.lock().unwrap().pop().expect("one request");
    assert_eq!(auth, "Bearer test-api-key");
    assert_eq!(body["model"], "audio-model-a");
    assert_eq!(body["modalities"], json!(["text"]));
    let content = &body["messages"][0]["content"];
    assert_eq!(content[0]["type"], "input_audio");
    let data = content[0]["input_audio"]["data"].as_str().unwrap();
    assert!(data.starts_with("data:audio/wav;base64,UklGR"), "{data}");
    assert_eq!(content[1]["text"], "What is said?");
}

#[tokio::test]
async fn undeclared_model_fails_before_any_request() {
    let run = setup(None);
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .respond_with(ResponseTemplate::new(500))
        .expect(0)
        .mount(&server)
        .await;

    ask(
        &run,
        &format!("{}/v1", server.uri()),
        "stepfun:audio-model-a",
    )
    .failure()
    .stderr(predicates::str::contains(
        "`stepfun:audio-model-a` has no audio input declared",
    ))
    .stderr(predicates::str::contains("`stepfun:stepaudio-2.5-chat`"));
}

/// `[providers.<name>.audio]` in config.toml changes the request without a
/// rebuild; fields it does not set keep the shipped defaults.
#[tokio::test]
async fn provider_audio_config_changes_the_request() {
    let run = setup_with_config(
        Some(
            r#"
[[override]]
id = "stepfun:audio-model-a"
input_audio = true
"#,
        ),
        Some(
            r#"
[providers.stepfun]
models = ["step-3.7-flash"]

[providers.stepfun.audio]
payload = "base64-with-format"
max_tokens = 123
text_modalities = false
"#,
        ),
    );
    let server = MockServer::start().await;
    let seen = mock_chat(&server).await;

    ask(
        &run,
        &format!("{}/v1", server.uri()),
        "stepfun:audio-model-a",
    )
    .success();

    let (_, body) = seen.lock().unwrap().pop().expect("one request");
    assert_eq!(body["max_tokens"], 123);
    assert!(body.get("modalities").is_none(), "{body}");
    let input_audio = &body["messages"][0]["content"][0]["input_audio"];
    assert_eq!(input_audio["format"], "wav");
    assert!(
        input_audio["data"].as_str().unwrap().starts_with("UklGR"),
        "{input_audio}"
    );
}

/// Runs `ask-media` on `clip` with only the given environment additions.
fn ask_custom(
    run: &Run,
    clip: &std::path::Path,
    model: &str,
    env: &[(&str, &str)],
) -> assert_cmd::assert::Assert {
    let mut cmd = crate::fixtures::zdx_cmd();
    cmd.env("ZDX_HOME", run.home.path())
        .env_remove("ACME_AUDIO_KEY")
        .current_dir(run.work.path());
    for (key, value) in env {
        cmd.env(key, value);
    }
    cmd.args([
        "ask-media",
        "--json",
        "-m",
        model,
        "-p",
        "What is said?",
        clip.to_str().unwrap(),
    ])
    .assert()
}

fn custom_provider_config(server: &MockServer, audio: &str) -> String {
    format!(
        "[providers.custom.acme-audio]\nbase_url = \"{}/v1\"\napi_key_env = \"ACME_AUDIO_KEY\"\nmodels = []\n\n[providers.custom.acme-audio.audio]\n{audio}",
        server.uri()
    )
}

const ACME_OVERRIDE: &str = r#"
[[override]]
id = "acme-audio:listen-1"
input_audio = true
"#;

/// A provider and model that exist only in temp config: the endpoint, the
/// credential env var, and every audio setting reach the request.
#[tokio::test]
async fn new_custom_provider_and_model_work_from_config_only() {
    let server = MockServer::start().await;
    let seen = mock_chat(&server).await;
    let run = setup_with_config(
        Some(ACME_OVERRIDE),
        Some(&custom_provider_config(
            &server,
            "payload = \"data-uri-with-format\"\nformats = [\"wav\"]\nmax_tokens = 77\ntext_modalities = true\n",
        )),
    );

    let output = ask_custom(
        &run,
        &run.clip,
        "acme-audio:listen-1",
        &[("ACME_AUDIO_KEY", "acme-key")],
    )
    .success()
    .get_output()
    .stdout
    .clone();
    let answer: Value = serde_json::from_slice(&output).unwrap();
    assert_eq!(answer["answer"], "silence");

    let (auth, body) = seen.lock().unwrap().pop().expect("one request");
    assert_eq!(auth, "Bearer acme-key");
    assert_eq!(body["model"], "listen-1");
    assert_eq!(body["max_tokens"], 77);
    assert_eq!(body["modalities"], json!(["text"]));
    let input_audio = &body["messages"][0]["content"][0]["input_audio"];
    assert_eq!(input_audio["format"], "wav");
    assert!(
        input_audio["data"]
            .as_str()
            .unwrap()
            .starts_with("data:audio/wav;base64,UklGR"),
        "{input_audio}"
    );
}

/// A format the custom provider does not list is converted to WAV first.
#[tokio::test]
async fn custom_provider_gets_unlisted_formats_as_wav() {
    let server = MockServer::start().await;
    let seen = mock_chat(&server).await;
    let run = setup_with_config(
        Some(ACME_OVERRIDE),
        Some(&custom_provider_config(
            &server,
            "payload = \"base64-with-format\"\nformats = [\"wav\"]\n",
        )),
    );
    let ogg = run.work.path().join("clip.ogg");
    let made = std::process::Command::new("ffmpeg")
        .args([
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
        ])
        .arg("anullsrc=r=48000:cl=mono")
        .args(["-t", "0.2", "-c:a", "libopus"])
        .arg(&ogg)
        .status();
    if !made.is_ok_and(|status| status.success()) {
        eprintln!("skipping: ffmpeg with libopus is not available");
        return;
    }

    ask_custom(
        &run,
        &ogg,
        "acme-audio:listen-1",
        &[("ACME_AUDIO_KEY", "acme-key")],
    )
    .success();

    let (_, body) = seen.lock().unwrap().pop().expect("one request");
    let input_audio = &body["messages"][0]["content"][0]["input_audio"];
    assert_eq!(input_audio["format"], "wav");
    assert!(
        input_audio["data"].as_str().unwrap().starts_with("UklGR"),
        "{input_audio}"
    );
}

/// `(audio block, model overrides, model, env, expected stderr)`.
type ErrorCase<'a> = (
    &'a str,
    Option<&'a str>,
    &'a str,
    &'a [(&'a str, &'a str)],
    &'a str,
);

/// Size limits, invalid settings, a missing credential, and an undeclared
/// model all fail before any request is sent.
#[tokio::test]
async fn custom_provider_errors_fail_before_any_request() {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .respond_with(ResponseTemplate::new(500))
        .expect(0)
        .mount(&server)
        .await;
    let key = [("ACME_AUDIO_KEY", "acme-key")];
    let cases: [ErrorCase<'_>; 5] = [
        (
            "payload = \"base64\"\nformats = [\"wav\"]\nmax_base64_bytes = 16\n",
            Some(ACME_OVERRIDE),
            "acme-audio:listen-1",
            &key,
            "acme-audio accepts at most",
        ),
        (
            "payload = \"raw\"\nformats = [\"wav\"]\n",
            Some(ACME_OVERRIDE),
            "acme-audio:listen-1",
            &key,
            "[providers.custom.acme-audio.audio] has unknown `payload = \"raw\"`",
        ),
        (
            "payload = \"base64\"\nformats = [\"mp3\"]\n",
            Some(ACME_OVERRIDE),
            "acme-audio:listen-1",
            &key,
            "must include `wav`",
        ),
        (
            "payload = \"base64\"\nformats = [\"wav\"]\n",
            Some(ACME_OVERRIDE),
            "acme-audio:listen-1",
            &[],
            "custom provider API key env var `ACME_AUDIO_KEY` is not set",
        ),
        (
            "payload = \"base64\"\nformats = [\"wav\"]\n",
            None,
            "acme-audio:listen-1",
            &key,
            "`acme-audio:listen-1` has no audio input declared",
        ),
    ];
    for (audio, overrides, model, env, expected) in cases {
        let run = setup_with_config(overrides, Some(&custom_provider_config(&server, audio)));
        ask_custom(&run, &run.clip, model, env)
            .failure()
            .stderr(predicates::str::contains(expected));
    }
}
